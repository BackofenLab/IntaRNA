#!/usr/bin/env python3
"""Resolve a stable ViennaRNA 2.x release asset, or validate a pinned manifest."""
import argparse
import json
import os
from pathlib import Path
import re
from urllib.request import Request, urlopen


REPOSITORY = "https://github.com/ViennaRNA/ViennaRNA"
API = "https://api.github.com/repos/ViennaRNA/ViennaRNA/releases"
MINIMUM = (2, 7, 2)


def version_tuple(version):
    if not isinstance(version, str) or not re.fullmatch(r"2\.\d+\.\d+", version):
        raise ValueError("Expected a stable ViennaRNA 2.x version")
    result = tuple(map(int, version.split(".")))
    if result < MINIMUM:
        raise ValueError("The WASM build requires ViennaRNA >= 2.7.2")
    return result


def validate(manifest):
    """Accept only official release tarballs with an explicit SHA-256."""
    version = manifest["version"]
    version_tuple(version)
    expected = f"{REPOSITORY}/releases/download/v{version}/ViennaRNA-{version}.tar.gz"
    if manifest["url"] != expected:
        raise ValueError("Expected the official ViennaRNA release asset URL")
    if not isinstance(manifest["sha256"], str) or not re.fullmatch(r"[0-9a-f]{64}", manifest["sha256"]):
        raise ValueError("Missing or invalid ViennaRNA archive SHA-256")
    return {key: manifest[key] for key in ("version", "url", "sha256")}


def latest_release():
    # Enumerate all pages: /latest may select major 3, and release dates need not
    # follow version order (for example, a maintenance release of an older minor).
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "IntaRNA-WASM"}
    if os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {os.environ['GITHUB_TOKEN']}"
    candidates = []
    page = 1
    while True:
        request = Request(f"{API}?per_page=100&page={page}", headers=headers)
        with urlopen(request, timeout=30) as response:
            releases = json.load(response)
        if not isinstance(releases, list):
            raise ValueError("Expected a GitHub release list")
        for release in releases:
            tag = release.get("tag_name", "")
            if release.get("draft") or release.get("prerelease") or not re.fullmatch(r"v2\.\d+\.\d+", tag):
                continue
            version = tag[1:]
            if tuple(map(int, version.split("."))) >= MINIMUM:
                candidates.append(release)
        if len(releases) < 100:
            break
        page += 1
    if not candidates:
        raise ValueError("No stable ViennaRNA 2.x release >= 2.7.2 was found")
    release = max(candidates, key=lambda item: version_tuple(item["tag_name"][1:]))
    version = release["tag_name"][1:]
    # Fail if the newest release lacks the asset/digest; do not silently select
    # an older release or GitHub's differently packaged autogenerated source.
    name = f"ViennaRNA-{version}.tar.gz"
    assets = [asset for asset in release.get("assets", []) if asset["name"] == name]
    if len(assets) != 1:
        raise ValueError(f"Expected exactly one {name} release asset")
    asset = assets[0]
    digest = asset.get("digest") or ""
    if not digest.startswith("sha256:"):
        raise ValueError(f"Missing published SHA-256 for {name}")
    return validate({"version": version, "url": asset["browser_download_url"], "sha256": digest[7:]})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--latest", action="store_true", help="query the official GitHub releases API")
    source.add_argument("--manifest", type=Path, default=Path(__file__).with_suffix(".json"))
    parser.add_argument("--fields", action="store_true", help="emit version, URL and SHA-256 for build.sh")
    args = parser.parse_args()
    try:
        manifest = latest_release() if args.latest else validate(json.loads(args.manifest.read_text()))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"Cannot resolve ViennaRNA release: {error}\n")
    print(" ".join(manifest.values()) if args.fields else json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
